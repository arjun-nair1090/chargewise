#!/usr/bin/env python3
"""Generate the synthetic ChargeWise demo dataset.

Every record is synthetic and labelled ``"synthetic": true``. Station sites use real Mumbai/Pune
locality coordinates but are not real charging stations; vehicle specs approximate common Indian
EV classes without naming any manufacturer. The output is deterministic for a given seed, so the
committed JSON can be regenerated byte-for-byte:

    python scripts/generate_dataset.py --seed 20261102 --out datasets

Charging-request windows are stored as offsets (multiples of 15 minutes) from the next slot boundary
at load time, so the demo data never goes stale (architecture D2).
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

SLOT_MINUTES = 15
MAX_WINDOW_SLOTS = 48
HORIZON_SLOTS = 96  # requests start within the next 24 hours

# (locality, city, latitude, longitude)
SITES = [
    ("Andheri East", "Mumbai", 19.1136, 72.8697),
    ("Bandra Kurla Complex", "Mumbai", 19.0662, 72.8654),
    ("Lower Parel", "Mumbai", 18.9953, 72.8300),
    ("Powai", "Mumbai", 19.1176, 72.9060),
    ("Vashi", "Navi Mumbai", 19.0771, 72.9986),
    ("Thane West", "Thane", 19.2183, 72.9781),
    ("Goregaon East", "Mumbai", 19.1663, 72.8526),
    ("Hinjewadi Phase 1", "Pune", 18.5913, 73.7389),
    ("Kharadi", "Pune", 18.5515, 73.9348),
    ("Baner", "Pune", 18.5590, 73.7868),
    ("Viman Nagar", "Pune", 18.5679, 73.9143),
    ("Kothrud", "Pune", 18.5074, 73.8077),
]

# connector type -> (relative weight, available power ratings in kW)
CONNECTOR_MIX = {
    "CCS2": (40, [30.0, 60.0, 120.0]),
    "TYPE2_AC": (30, [7.4, 22.0]),
    "BHARAT_AC001": (10, [3.3]),
    "BHARAT_DC001": (10, [15.0]),
    "CHADEMO": (10, [50.0]),
}

# (class label, battery kWh, max charging kW, connector types)
VEHICLE_CLASSES = [
    ("hatchback", 26.0, 25.0, ["CCS2", "TYPE2_AC"]),
    ("compact SUV", 40.5, 50.0, ["CCS2", "TYPE2_AC"]),
    ("sedan", 39.2, 50.0, ["CCS2", "TYPE2_AC"]),
    ("mid-size SUV", 50.3, 76.0, ["CCS2", "TYPE2_AC"]),
    ("fleet sedan", 21.2, 15.0, ["BHARAT_DC001", "BHARAT_AC001"]),
    ("legacy import", 40.0, 50.0, ["CHADEMO", "TYPE2_AC"]),
]

RTO_CODES = ["01", "02", "03", "04", "05", "12", "14", "43", "46", "47"]

DRIVER_COUNT = 20
VEHICLES_PER_DRIVER = 2
REQUEST_COUNT = 120


def stations(rng: random.Random) -> list[dict]:
    result = []
    for index, (locality, city, lat, lng) in enumerate(SITES, start=1):
        result.append({
            "id": f"S-{index:02d}",
            "name": f"ChargeWise Demo Hub {locality}",
            "address": f"Synthetic site, {locality}, {city}, Maharashtra",
            "latitude": lat,
            "longitude": lng,
            "gridCapacityKw": float(rng.randrange(60, 601, 10)),
            # One site under maintenance shows the STATION_NOT_OPERATIONAL path in the demo.
            "status": "MAINTENANCE" if index == 7 else "OPERATIONAL",
            "synthetic": True,
        })
    return result


def connectors(rng: random.Random, station_rows: list[dict]) -> list[dict]:
    types = list(CONNECTOR_MIX)
    weights = [CONNECTOR_MIX[t][0] for t in types]
    result = []
    for station in station_rows:
        count = rng.randint(3, 6)
        # Every hub offers at least one CCS2 connector, the dominant DC standard in India.
        chosen = ["CCS2"] + rng.choices(types, weights=weights, k=count - 1)
        for connector_type in chosen:
            result.append({
                "id": f"C-{len(result) + 1:03d}",
                "stationId": station["id"],
                "connectorType": connector_type,
                "maxPowerKw": rng.choice(CONNECTOR_MIX[connector_type][1]),
                "status": "OUT_OF_SERVICE" if rng.random() < 0.06 else "OPERATIONAL",
                "synthetic": True,
            })
    return result


def registration(rng: random.Random, used: set[str]) -> str:
    while True:
        letters = "".join(rng.choice("ABCDEFGHJKLMNPRSTUVWXYZ") for _ in range(2))
        plate = f"MH{rng.choice(RTO_CODES)}{letters}{rng.randint(1000, 9999)}"
        if plate not in used:
            used.add(plate)
            return plate


def vehicles(rng: random.Random) -> list[dict]:
    used: set[str] = set()
    result = []
    for driver in range(1, DRIVER_COUNT + 1):
        for _ in range(VEHICLES_PER_DRIVER):
            label, battery, max_kw, plug_types = rng.choice(VEHICLE_CLASSES)
            result.append({
                "registrationNumber": registration(rng, used),
                "ownerEmail": f"driver{driver:02d}@demo.chargewise.test",
                "ownerName": f"Demo Driver {driver:02d}",
                "vehicleClass": label,
                "batteryCapacityKwh": battery,
                "currentSoc": round(rng.uniform(5.0, 80.0), 1),
                "maxChargingKw": max_kw,
                "connectorTypes": plug_types,
                "synthetic": True,
            })
    return result


def overlaps(windows: list[tuple[int, int]], start: int, end: int) -> bool:
    return any(start < other_end and other_start < end for other_start, other_end in windows)


def charging_requests(rng: random.Random, vehicle_rows: list[dict], station_rows: list[dict]) -> list[dict]:
    windows: dict[str, list[tuple[int, int]]] = {v["registrationNumber"]: [] for v in vehicle_rows}
    result = []
    while len(result) < REQUEST_COUNT:
        vehicle = rng.choice(vehicle_rows)
        start_slot = rng.randrange(1, HORIZON_SLOTS)
        slots = rng.randint(2, 12)
        if slots > MAX_WINDOW_SLOTS or overlaps(windows[vehicle["registrationNumber"]], start_slot, start_slot + slots):
            continue
        hours = slots * SLOT_MINUTES / 60
        headroom = vehicle["batteryCapacityKwh"] * (100 - vehicle["currentSoc"]) / 100
        deliverable = vehicle["maxChargingKw"] * hours
        ceiling = min(headroom, deliverable)
        if ceiling < 5.0:
            continue
        # Half-kWh steps rounded down keep every request within headroom and deliverable energy.
        energy = int(rng.uniform(5.0, ceiling) * 2) / 2
        windows[vehicle["registrationNumber"]].append((start_slot, start_slot + slots))
        result.append({
            "id": f"R-{len(result) + 1:04d}",
            "registrationNumber": vehicle["registrationNumber"],
            "stationId": rng.choice(station_rows)["id"],
            "requestedEnergyKwh": energy,
            "startOffsetMinutes": start_slot * SLOT_MINUTES,
            "durationMinutes": slots * SLOT_MINUTES,
            "synthetic": True,
        })
    return result


def write_json(path: Path, rows: list[dict]) -> None:
    path.write_text(json.dumps(rows, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", type=int, default=20261102)
    parser.add_argument("--out", type=Path, default=Path("datasets"))
    args = parser.parse_args()

    rng = random.Random(args.seed)
    station_rows = stations(rng)
    connector_rows = connectors(rng, station_rows)
    vehicle_rows = vehicles(rng)
    request_rows = charging_requests(rng, vehicle_rows, station_rows)

    args.out.mkdir(parents=True, exist_ok=True)
    write_json(args.out / "stations.json", station_rows)
    write_json(args.out / "connectors.json", connector_rows)
    write_json(args.out / "vehicles.json", vehicle_rows)
    write_json(args.out / "charging_requests.json", request_rows)
    print(f"seed {args.seed}: {len(station_rows)} stations, {len(connector_rows)} connectors, "
          f"{len(vehicle_rows)} vehicles, {len(request_rows)} charging requests -> {args.out}")


if __name__ == "__main__":
    main()
